package dev.groknull.kludgeworks.build;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Arrays;
import java.util.HexFormat;

/**
 * Writes a Java class that gives the SHA-256 of some source files: a version of what they do, which
 * changes when any of them changes. The files are hashed in the order of their paths, each with its
 * name, so that the version does not depend on the order of the arguments.
 *
 * <p>Usage: {@code SourceDigest <out.java> <package> <class> <file>…}
 */
public final class SourceDigest {

  /** How many hex digits of the SHA-256 the version keeps: enough to tell versions apart. */
  private static final int DIGITS = 16;

  private SourceDigest() {}

  public static void main(String[] args) throws IOException, NoSuchAlgorithmException {
    if (args.length < 4) {
      throw new IllegalArgumentException(
          "Usage: SourceDigest <out.java> <package> <class> <file>…");
    }
    var out = Path.of(args[0]);
    var packageName = args[1];
    var className = args[2];
    var files = Arrays.stream(args, 3, args.length).sorted().map(Path::of).toList();
    var sha = MessageDigest.getInstance("SHA-256");
    for (var file : files) {
      sha.update(file.getFileName().toString().getBytes(StandardCharsets.UTF_8));
      sha.update((byte) 0);
      sha.update(Files.readAllBytes(file));
      sha.update((byte) 0);
    }
    var version = HexFormat.of().formatHex(sha.digest()).substring(0, DIGITS);
    Files.writeString(
        out,
        """
        // Generated by //tools/build/src/main/java/dev/groknull/kludgeworks/build:source_digest from
        // the sources of this package, when they are built. Do not edit.
        package PACKAGE;

        /**
         * The version of the rules in this package: the start of the SHA-256 of their sources. It
         * changes when any of them changes.
         */
        public final class CLASS {
          private CLASS() {}

          public static String value() {
            return "VERSION";
          }
        }
        """
            .replace("PACKAGE", packageName)
            .replace("CLASS", className)
            .replace("VERSION", version));
  }
}
